#!/usr/bin/env node
/** Generates src/tokens/tokens.d.ts (union of every --prism-* token) from prism-tokens.css. */
import { readFileSync, writeFileSync } from 'node:fs';

const css = readFileSync('src/tokens/prism-tokens.css', 'utf8');
const names = [...new Set([...css.matchAll(/(--prism-[a-z0-9-]+)\s*:/g)].map((m) => m[1]))].sort();
const body = names.map((n) => `  | '${n}'`).join('\n');
writeFileSync(
  'src/tokens/tokens.d.ts',
  `// Generated by scripts/generate-token-types.mjs from prism-tokens.css. Do not edit.\nexport type PrismToken =\n${body};\n`,
);
console.log(`tokens.d.ts: ${names.length} tokens`);
