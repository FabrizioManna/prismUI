#!/usr/bin/env node
/**
 * Builds src/tokens/prism-tokens.css from:
 *   1. src/tokens/source/visual-tokens.block.css — the Graphic Designer block, verbatim
 *      (`npm run tokens:sync -- --from ../prismUI-design/visual-tokens.md` refreshes it from the doc);
 *   2. src/tokens/source/extensions.css — prismUI extensions.
 * Then adds the theme selectors (architecture.md §7.6):
 *   - `[data-theme="light"]`: light values for a subtree inside a dark page;
 *   - `[data-theme="auto"]`: light by default, dark values under `@media (prefers-color-scheme: dark)`.
 * Rules listing `:root` together with the dark selectors are theme-independent and get both selectors;
 * dark-only rules get an `auto` copy inside `prefers-color-scheme: dark`, placed right after them.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import postcss from 'postcss';

const BLOCK = 'src/tokens/source/visual-tokens.block.css';
const EXT = 'src/tokens/source/extensions.css';
const OUT = 'src/tokens/prism-tokens.css';

const fromIdx = process.argv.indexOf('--from');
if (fromIdx > 0) {
  const md = readFileSync(process.argv[fromIdx + 1], 'utf8');
  const start = md.indexOf('### Blocco CSS pronto da incollare');
  const fence = md.indexOf('```css', start);
  const end = md.indexOf('```', fence + 6);
  if (start < 0 || fence < 0 || end < 0) throw new Error('CSS block not found in visual-tokens.md');
  writeFileSync(BLOCK, md.slice(fence + 6, end).replace(/^\n/, ''));
  console.log(`tokens:sync: ${BLOCK} refreshed from ${process.argv[fromIdx + 1]}`);
}

const DARK = ['.dark', '[data-theme="dark"]'];
const LIGHT = '[data-theme="light"]';
const AUTO = '[data-theme="auto"]';

function transform(root) {
  root.walkRules((rule) => {
    const sels = rule.selectors;
    const isDarkOnly = sels.length === DARK.length && DARK.every((d) => sels.includes(d));
    const hasDark = DARK.every((d) => sels.includes(d));
    if (hasDark && sels.includes(':root')) {
      rule.selectors = [...sels, LIGHT, AUTO];
      return;
    }
    if (sels.length === 1 && sels[0] === ':root') {
      // Light counterpart of a dark-only rule in the same context?
      const siblings = rule.parent.nodes.filter((n) => n.type === 'rule');
      const hasDarkSibling = siblings.some(
        (n) => n.selectors.length === 2 && DARK.every((d) => n.selectors.includes(d)),
      );
      if (hasDarkSibling) rule.selectors = [':root', LIGHT, AUTO];
      return;
    }
    if (isDarkOnly && !rule.__prismAuto) {
      const media = postcss.atRule({ name: 'media', params: '(prefers-color-scheme: dark)' });
      const copy = rule.clone({ selectors: [AUTO] });
      copy.__prismAuto = true;
      media.append(copy);
      rule.after(media);
    }
  });
  return root;
}

const header = `/*
 * prismUI design tokens (--prism-*). GENERATED by scripts/sync-tokens.mjs: do not edit.
 *
 * Source of truth: prismUI-design/visual-tokens.md §5 "Blocco CSS pronto da incollare" (Graphic Designer),
 * copied verbatim in src/tokens/source/visual-tokens.block.css, plus src/tokens/source/extensions.css.
 *
 * - Tokens live in the light DOM and reach shadow roots through custom-property inheritance.
 * - Themes: light on :root; dark with \`.dark\` or \`[data-theme="dark"]\`; \`[data-theme="light"]\` forces light
 *   in a subtree; \`[data-theme="auto"]\` follows prefers-color-scheme.
 * - Mobile first: touch defaults, refined in @media (pointer: fine) and min-width breakpoints.
 * - Text surfaces: --prism-glass-surface-solid-*; decorative: -deco-*; opaque fallback: --prism-surface-opaque-*.
 * - The class rules (.prism-glass, .prism-modal…) in the contrast/forced-colors blocks style the light DOM;
 *   components carry the same classes in their shadow roots and get the same rules from src/styles/surfaces.css.
 */

`;

/**
 * Class rules of the contrast / forced-colors blocks (.prism-glass, .prism-modal, [aria-pressed]…) only reach
 * the light DOM. Copy them, with their media conditions, into a stylesheet adopted by every shadow root.
 */
function shadowRules(root) {
  const out = postcss.root();
  root.each((node) => {
    if (node.type === 'rule' && node.selectors.every((sel) => sel.startsWith('::selection'))) {
      out.append(node.clone()); // ::selection in the document does not reach shadow trees
      return;
    }
    if (node.type !== 'atrule' || node.name !== 'media') return;
    const media = postcss.atRule({ name: 'media', params: node.params });
    node.each((child) => {
      if (child.type !== 'rule') return;
      const themed = child.selectors.some((s) => /:root|\.dark|data-theme/.test(s));
      const tokensOnly = child.nodes.every((d) => d.type !== 'decl' || d.prop.startsWith('--'));
      if (!themed && !tokensOnly) media.append(child.clone());
    });
    if (media.nodes?.length) out.append(media);
  });
  return out;
}

const SURFACES = 'src/styles/surfaces.css';

const source = readFileSync(BLOCK, 'utf8') + '\n' + readFileSync(EXT, 'utf8');
const parsed = postcss.parse(source);
writeFileSync(
  SURFACES,
  `/*
 * GENERATED by scripts/sync-tokens.mjs from the token block: do not edit.
 * Stable surface/control classes (.prism-glass, .prism-modal, .prism-input…) for prefers-contrast: more and
 * forced-colors: active, adopted by every shadow root through base.css (light-DOM rules do not pierce shadows).
 */

` +
    shadowRules(parsed).toString().trim() +
    '\n',
);
const result = transform(parsed).toString();
writeFileSync(OUT, header + result.trim() + '\n');
console.log(`tokens:sync: ${OUT} written`);
